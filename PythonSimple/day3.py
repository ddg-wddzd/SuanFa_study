#编写一个程序：1
#提示用户输入一个圆的半径（可能是小数）。
#计算并输出圆的面积（公式 π * r²，π 取 3.14）。
#要求处理输入无效的情况（例如用户输入字母），如果输入无效，输出“半径必须为数字”并让程序正常结束（不崩溃）。
r=input("请输入圆的半径：")
try:
    radius=float(r)
    area=radius**2*3.14
    print(f"圆的面积：{area:.2f}") #:.2f表示保留两位小数
except ValueError:
    print("半径必须为数字")
